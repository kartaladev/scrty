// Cipher seals and opens the long-lived secrets a durable store keeps, binding
// each value to the record it belongs to through additional authenticated data
// (aad), which is authenticated but not stored.
//
// NewAEADCipher returns the default, AES-256-GCM over a Keyring. A consumer
// replaces it wholesale by implementing this interface, for example over a
// key management service; nothing else in the library assumes AES. An
// implementation must be safe for concurrent use, must make Open fail when aad
// differs from what Seal was given, and should produce a different value each
// time it seals the same plaintext.
//
//go:generate mockgen -source=cipher.go -package=seal_test -destination=cipher_mock_test.go -typed
type Cipher interface {
	// Seal encrypts plaintext under the active key, authenticating aad.
	Seal(plaintext, aad []byte) ([]byte, error)

	// Open decrypts sealed, failing unless aad is exactly what Seal was given,
	// and reports the id of the key that opened it, so a caller can tell a
	// value sealed under a retired key and re-seal it.
	Open(sealed, aad []byte) (plaintext []byte, keyID string, err error)

	// ActiveKeyID returns the id of the key Seal uses now.
	ActiveKeyID() (string, error)
}

// aeadCipher is the default Cipher.
type aeadCipher struct {
	kr Keyring
}

// NewAEADCipher returns the default Cipher: AES-256-GCM with a fresh random
// 96-bit nonce for every seal, drawn from crypto/rand, over the keys of kr.
// A consumer who wants another algorithm or a key management service
// implements Cipher instead; one who keeps the keys elsewhere supplies their
// own Keyring.
//
// It returns an error matching ErrConfig when kr is nil, typed
// nil included, so a cipher wired without keys fails at start-up rather than on
// the first seal or open.
//
// Values are stored as an envelope naming the key that sealed them, so kr may
// gain an active key and keep the old one as retired without making stored
// values unreadable. The envelope's header, key id included, is authenticated
// together with aad, so a value whose key id was rewritten does not open even
// under a keyring that returns the same bytes for two ids.
//
// kr is asked for a key on every call and is never cached. A key that is not
// 32 bytes, or an active key id outside [A-Za-z0-9._-]{1,64}, fails the call
// with ErrConfig; the cipher never falls back to a shorter key or
// to storing plaintext.
//
// Open returns ErrDecryptionFailed for every value that does not open — wrong
// key, wrong aad, altered or truncated bytes, or bytes that were never sealed —
// and ErrUnknownKeyID, never matching ErrDecryptionFailed, when the value
// names a key kr does not hold. With ErrUnknownKeyID it still returns the id
// the value names, so an operator can tell which key to restore; that id is
// read from the stored value and is never part of the error's text (see
// ErrUnknownKeyID). A failure of kr itself is returned behind fixed text,
// matching the ring's error through errors.Is and errors.As. No error carries
// key bytes or plaintext.
//
// Limit: a random 96-bit nonce is safe for about 2^32 seals under one key;
// past that, the chance of a repeated nonce, which breaks GCM's
// confidentiality and integrity for that key, is no longer negligible. Rotate
// the active key well before a key has sealed that many values.
func NewAEADCipher(kr Keyring) (Cipher, error) {
	if nilcheck.IsNil(kr) {
		return nil, fmt.Errorf("%w: the cipher has no keyring", ErrConfig)
	}

	return &aeadCipher{kr: kr}, nil
}

// Seal encrypts plaintext under the active key and returns the envelope.
func (c *aeadCipher) Seal(plaintext, aad []byte) ([]byte, error) {
	id, key, err := c.active()
	if err != nil {
		return nil, err
	}

	aead, err := newAEAD(key)
	if err != nil {
		return nil, err
	}

	// The nonce is generated by the AEAD and written ahead of the ciphertext,
	// which is exactly the envelope's body. The header is authenticated with
	// the caller's aad, so a rewritten key id fails the tag.
	header := encodeHeader(id, len(plaintext))

	return aead.Seal(header, nil, plaintext, additionalData(header, aad)), nil //nolint:gosec // G407: NewGCMWithRandomNonce generates the nonce, so Seal takes none
}

// Open decrypts an envelope, reporting the id of the key that opened it.
func (c *aeadCipher) Open(sealed, aad []byte) ([]byte, string, error) {
	id, header, body, ok := decodeEnvelope(sealed)
	if !ok {
		return nil, "", ErrDecryptionFailed
	}

	key, err := c.kr.ByID(id)
	if errors.Is(err, ErrUnknownKeyID) {
		return nil, id, diag.Wrap(err, "seal: unknown key id: the keyring does not hold the key the value was sealed under",
			ErrUnknownKeyID)
	}
	if err != nil {
		return nil, "", diag.Wrap(err, "seal: the keyring could not provide the key the value was sealed under")
	}

	aead, err := newAEAD(key)
	if err != nil {
		return nil, "", err
	}

	plaintext, err := aead.Open(nil, nil, body, additionalData(header, aad))
	if err != nil {
		return nil, "", ErrDecryptionFailed
	}

	return plaintext, id, nil
}

// ActiveKeyID returns the id of the keyring's active key.
func (c *aeadCipher) ActiveKeyID() (string, error) {
	id, _, err := c.active()

	return id, err
}

// active asks the keyring for its active key, and refuses an id the envelope
// cannot carry. It is the one place a keyring's active key is checked, so
// Seal and ActiveKeyID can never disagree about it.
func (c *aeadCipher) active() (string, []byte, error) {
	id, key, err := c.kr.Active()
	if err != nil {
		return "", nil, diag.Wrap(err, "seal: the keyring could not provide the active key")
	}
	if !validKeyID(id) {
		return "", nil, fmt.Errorf("%w: the active key id must be 1 to %d of A-Z, a-z, 0-9, '.', '_' or '-'",
			ErrConfig, maxKeyIDLen)
	}

	return id, key, nil
}

// newAEAD returns AES-256-GCM over key, generating a random nonce on each
// seal. A key of any other length is refused, so a consumer's keyring cannot
// quietly downgrade the cipher to AES-128 or AES-192.
func newAEAD(key []byte) (cipher.AEAD, error) {
	if len(key) != KeySize {
		return nil, fmt.Errorf("%w: a key must be %d bytes, got %d", ErrConfig, KeySize, len(key))
	}

	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, diag.Wrap(err, "seal: the key could not be used", ErrConfig)
	}

	aead, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, diag.Wrap(err, "seal: the key could not be used", ErrConfig)
	}

	return aead, nil
}

// The envelope is the stored form of a sealed value:
//
//	magic(4) | keyIDLen(1) | keyID | nonce(12) | ciphertext‖tag(16)
//
// The magic turns "this was never a sealed value" into a refusal before any
// key is looked up. The key id says which key opens the value, which is what
// lets a keyring keep old keys for reading after a rotation.
//
// The header (magic‖keyIDLen‖keyID) is covered by the GCM tag: it is
// authenticated as additional data ahead of the caller's aad, so an altered
// key id fails the tag even when a consumer keyring returns the same bytes for
// two ids, and an altered nonce fails it too. The one alteration reported
// before any tag check is a key id the keyring does not hold, which is
// ErrUnknownKeyID; the id it reports is read from the stored value.
const (
	envelopeMagic = "SCS1"
	nonceSize     = 12
	tagSize       = 16

	// minBody is the shortest nonce‖ciphertext‖tag: an empty plaintext.
	minBody = nonceSize + tagSize
)

// encodeHeader returns a slice holding the envelope header for keyID, with
// capacity for a body sealing bodyPlaintext bytes. keyID must already be
// valid, so its length fits the one-byte field.
func encodeHeader(keyID string, bodyPlaintext int) []byte {
	out := make([]byte, 0, len(envelopeMagic)+1+len(keyID)+minBody+bodyPlaintext)
	out = append(out, envelopeMagic...)
	out = append(out, byte(len(keyID))) //nolint:gosec // G115: callers pass a validated id of at most 64 bytes

	return append(out, keyID...)
}

// decodeEnvelope splits sealed into its key id, its header
// (magic‖keyIDLen‖keyID) and its body (nonce‖ciphertext‖tag). ok is false for
// anything that is not a well-formed envelope: no magic, a key-id length of
// zero or past the end, a key id outside the allowed characters, or a body too
// short to hold a nonce and a tag. Every length is checked before the slice it
// bounds is taken.
func decodeEnvelope(sealed []byte) (keyID string, header, body []byte, ok bool) {
	const fixed = len(envelopeMagic) + 1

	if len(sealed) < fixed || string(sealed[:len(envelopeMagic)]) != envelopeMagic {
		return "", nil, nil, false
	}

	n := int(sealed[len(envelopeMagic)])
	if n == 0 || len(sealed)-fixed < n+minBody {
		return "", nil, nil, false
	}

	keyID = string(sealed[fixed : fixed+n])
	if !validKeyID(keyID) {
		return "", nil, nil, false
	}

	return keyID, sealed[:fixed+n], sealed[fixed+n:], true
}

// additionalData returns the GCM additional data for a value: the envelope
// header followed by the caller's aad, in a new slice so neither is aliased.
// Covering the header binds the key id to the ciphertext, so a value whose id
// was rewritten fails the tag even under a keyring that returns the same bytes
// for both ids. The header has a fixed-width magic and a length-prefixed id,
// so no header‖aad pair can be read as a different split of the same bytes.
func additionalData(header, aad []byte) []byte {
	out := make([]byte, 0, len(header)+len(aad))
	out = append(out, header...)

	return append(out, aad...)
}

// The additional authenticated data each sealed column is bound to. A value
// opens only with the exact data it was sealed with, so a sealed value copied
// to another row, or to another table, will not open there.
//
// They follow the scrty/<package>:<field>: form the sealing session store
// already binds provider ID tokens with ("scrty/session:external-id-token:"
// followed by the session identifier), so the three read as one convention.
//
// They are part of the stored format, not configuration: changing one makes
// every stored value unopenable, which cannot be told apart from tampering.
// A consumer cipher receives the full additional data and may use it, but
// must not rewrite it.
const (
	// AADSigningKeyPrefix is followed by the signing key's id.
	AADSigningKeyPrefix = "scrty/signingkey:private:"

	// AADMFASecretPrefix is followed by the enrolment's generation, in its
	// canonical 36-character text form, a ':' and the enrolled user's
	// reference, byte for byte.
	AADMFASecretPrefix = "scrty/mfa:secret:" //nolint:gosec // G101: an additional-data prefix, not a credential

	// AADMFAEmailCodePrefix is followed by the enrolment's generation, in its
	// canonical 36-character text form, a ':' and the user reference, byte
	// for byte.
	AADMFAEmailCodePrefix = "scrty/mfa:email-code:"

	// AADPasskeyEmailCodePrefix is followed by the passkey credential's
	// library identifier, in its canonical 36-character text form, a ':' and
	// the user reference, byte for byte.
	AADPasskeyEmailCodePrefix = "scrty/passkey:email-code:" //nolint:gosec // G101: an AAD prefix, not a credential
)

// SigningKeyAAD returns the additional data a signing key's private material
// is sealed against: AADSigningKeyPrefix followed by kid, byte for byte.
func SigningKeyAAD(kid string) []byte {
	return []byte(AADSigningKeyPrefix + kid)
}

// MFASecretAAD returns the additional data a user's MFA secret is sealed
// against: AADMFASecretPrefix followed by the enrolment generation gen and the
// user reference, byte for byte, never trimmed or case-folded. The
// fixed-length generation precedes the free-form user reference, so no two
// (generation, user) pairs share additional data.
//
// Binding the generation is what keeps a secret the user gave up, by removing
// the enrolment or beginning again, from opening if its ciphertext is copied
// back onto the same user's later enrolment. A secret sealed before the
// generation was part of this binding, against the user reference alone, does
// not open under it: a user whose enrolment was sealed that way must enrol
// again.
func MFASecretAAD(gen id.ID, user identity.UserID) []byte {
	return []byte(AADMFASecretPrefix + gen.String() + ":" + string(user))
}

// MFAEmailCodeAAD returns the additional data an emailed enrolment code is
// sealed against. The fixed-length generation precedes the free-form user
// reference, so no two (generation, user) pairs share additional data.
func MFAEmailCodeAAD(gen id.ID, user identity.UserID) []byte {
	return []byte(AADMFAEmailCodePrefix + gen.String() + ":" + string(user))
}

// PasskeyEmailCodeAAD returns the additional data the code emailed to confirm
// a pending passkey is sealed against. The fixed-length credential identifier
// precedes the free-form user reference, so no two (credential, user) pairs
// share additional data.
func PasskeyEmailCodeAAD(cid id.ID, user identity.UserID) []byte {
	return []byte(AADPasskeyEmailCodePrefix + cid.String() + ":" + string(user))
}

// sessionCipher adapts a Cipher to session.Cipher, which has no use for the
// id of the key that opened a value: sessions are never re-sealed on read.
type sessionCipher struct {
	c Cipher
}

// SessionCipher adapts c to the session.Cipher port, so a durable session
// store seals the provider ID token through session.NewEncryptedStore:
//
//	store, err := session.NewEncryptedStore(inner, seal.SessionCipher(c))
//
// The sealing rule for sessions, including the additional data each token is
// bound to, stays in package session; this adapter only drops the key id Open
// reports. c's errors are returned unchanged, and the session store answers a
// token that will not open as session.ErrUnreadable.
//
// A nil c, typed nil included, gives a nil session.Cipher, so
// session.NewEncryptedStore refuses it with session.ErrConfig instead of the
// first seal panicking.
func SessionCipher(c Cipher) session.Cipher {
	if nilcheck.IsNil(c) {
		return nil
	}

	return sessionCipher{c: c}
}

// Seal seals plaintext through the wrapped Cipher.
func (s sessionCipher) Seal(plaintext, additionalData []byte) ([]byte, error) {
	return s.c.Seal(plaintext, additionalData)
}

// Open opens ciphertext through the wrapped Cipher, dropping the key id.
func (s sessionCipher) Open(ciphertext, additionalData []byte) ([]byte, error) {
	plaintext, _, err := s.c.Open(ciphertext, additionalData)

	return plaintext, err
}
